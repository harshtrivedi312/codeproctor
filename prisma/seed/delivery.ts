// Delivery rows of the seed (DB-04): 5 candidates, 7 invitations with their sessions, and for the
// three sessions that finished the test: signed consents, identity checks, sections, served
// questions, submissions, proctor events with their batches, a risk score each, and one completed
// review with flag decisions. A pure function of `now` and the content plan.
//
// Reading of the prompt (recorded in the PR): "5 candidates in different states (INVITED, CONSENTED,
// EXPIRED, DECLINED, COMPLETED)" and "3 completed sessions, a risk score in each band, one completed
// review" are met by 7 sessions. ADR 0002 section 2 lets a MEDIUM or HIGH session reach COMPLETED
// only through a verdict, and the prompt allows one completed review, so of the three finished
// sessions one is LOW and COMPLETED, one is MEDIUM and COMPLETED with the review, and one is HIGH and
// UNDER_REVIEW (waiting for a reviewer).
