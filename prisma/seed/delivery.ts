export interface PlannedEvent {
  /**
   * Stable lookup key: session id, type, and the event's rank among the events of that type in the
   * session by time. It does not depend on the run time, so a second run finds the events a first
   * run stored (the id is generated by the database).
   */
  readonly key: string;
  readonly row: Omit<Prisma.ProctorEventCreateManyInput, 'id'>;
}

export interface PlannedFlagDecision {
  readonly eventKey: string;
  readonly row: Omit<Prisma.FlagDecisionCreateManyInput, 'eventId'>;
}

export interface DeliveryPlan {
  readonly candidates: Prisma.CandidateCreateManyInput[];
  readonly invitations: Prisma.InvitationCreateManyInput[];
  readonly sessions: Prisma.SessionCreateManyInput[];
  readonly sessionSections: Prisma.SessionSectionCreateManyInput[];
  readonly sessionQuestions: Prisma.SessionQuestionCreateManyInput[];
  readonly submissions: Prisma.SubmissionCreateManyInput[];
  readonly consents: Prisma.ConsentCreateManyInput[];
  readonly identityChecks: Prisma.IdentityCheckCreateManyInput[];
  readonly proctorEventBatches: Prisma.ProctorEventBatchCreateManyInput[];
  readonly proctorEvents: PlannedEvent[];
  readonly sessionReviews: Prisma.SessionReviewCreateManyInput[];
  readonly flagDecisions: PlannedFlagDecision[];
  readonly auditLogs: Prisma.AuditLogCreateManyInput[];
}

